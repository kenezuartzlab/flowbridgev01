import fs from 'node:fs';
import path from 'node:path';
import solc from 'solc-0.8.20';
import { keccak256 } from 'viem';
const dir = 'contracts/production/rewards-vault-v2';
export function compile(extra = {}) {
 const sources = { 'FlowRewardsVaultV2.sol': { content: fs.readFileSync(`${dir}/FlowRewardsVaultV2.sol`, 'utf8') }, ...extra };
 const output = JSON.parse(solc.compile(JSON.stringify({language:'Solidity', sources, settings:{optimizer:{enabled:true,runs:200},evmVersion:'paris',outputSelection:{'*':{'*':['abi','evm.bytecode.object','evm.deployedBytecode.object','evm.deployedBytecode.immutableReferences']}}}}), {import:p=>{try{return {contents:fs.readFileSync(path.join('node_modules',p),'utf8')}}catch{return {error:`Missing ${p}`}}}}));
 const errors=(output.errors??[]).filter(e=>e.severity==='error'); if(errors.length) throw new Error(errors.map(e=>e.formattedMessage).join('\n'));
 return output.contracts;
}
if (process.argv[1]?.endsWith('compile.mjs')) {
 const c=compile()['FlowRewardsVaultV2.sol'].FlowRewardsVaultV2;
 fs.mkdirSync(`${dir}/artifacts`,{recursive:true});
 fs.writeFileSync(`${dir}/artifacts/FlowRewardsVaultV2.json`,JSON.stringify({compiler:solc.version(),openzeppelin:'5.0.2',optimizerRuns:200,evmVersion:'paris',...c},null,2));
 fs.writeFileSync('src/lib/rewards/vaultV2Abi.generated.ts',`// Generated by contracts/production/rewards-vault-v2/scripts/compile.mjs. Do not hand-edit.\nexport const VAULT_V2_ABI = ${JSON.stringify(c.abi,null,2)} as const;\n`);
 console.log(`Vault compiled; unpatched runtime hash ${keccak256('0x'+c.evm.deployedBytecode.object)} (deployment immutable FLOW must be patched before comparison)`);
}
