// Generates src/lib/rewards/vaultV2Runtime.generated.ts from the frozen artifact.
// The app derives the expected deployed runtime only from this unpatched runtime and its immutable slots.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
const here = dirname(fileURLToPath(import.meta.url));
const artifact = JSON.parse(readFileSync(join(here, '../verification/artifact.json'), 'utf8'));
const runtime = artifact.evm.deployedBytecode;
const slots = Object.values(runtime.immutableReferences).flat();
if (Object.keys(runtime.immutableReferences).length !== 1 || slots.length !== 7 || slots.some(s => s.length !== 32)) throw new Error('Unexpected immutable layout');
const out = `// GENERATED by contracts/production/rewards-vault-v2/scripts/runtime-module.mjs from verification/artifact.json. Do not edit.
export const VAULT_V2_COMPILER = ${JSON.stringify(artifact.compiler)};
export const VAULT_V2_OPENZEPPELIN = ${JSON.stringify(artifact.openzeppelin)};
export const VAULT_V2_UNPATCHED_RUNTIME = '0x${runtime.object}' as const;
export const VAULT_V2_FLOW_IMMUTABLE_OFFSETS = ${JSON.stringify(slots.map(s => s.start))} as const;
`;
writeFileSync(join(here, '../../../../src/lib/rewards/vaultV2Runtime.generated.ts'), out);
console.log('runtime bytes', runtime.object.length / 2, 'slots', slots.map(s => s.start).join(','));
